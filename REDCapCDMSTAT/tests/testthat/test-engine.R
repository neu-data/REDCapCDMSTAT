demo <- function() cdmstat_demo(dir = file.path(tempfile("nx")), actor = "tester")

test_that("validation finds every planted problem in the demo project", {
  nx <- demo()
  iss <- nx$validate()
  has <- function(rule, rec) any(iss$rule == rule & iss$record_id == rec)
  expect_true(has("range:weight", "7"))
  expect_true(has("range:sbp", "15"))
  expect_true(has("branching:pregnant", "22"))
  expect_true(has("calc:bmi", "31"))
  expect_true(has("required:site", "40"))
  expect_true(has("custom:sbp_gt_dbp", "63"))
  expect_true(has("range:height", "77"))
  expect_false(any(duplicated(iss$issue_key)))
})

test_that("incremental sync patches edits and auto-resolves fixed queries", {
  nx <- demo()
  r <- nx$raise_queries()
  expect_gt(r$created, 0)
  nx$backend$edit("7", "weight", "75.0")
  s <- nx$sync()
  expect_equal(s$mode, "incremental")
  expect_equal(s$changed, 1)
  w <- nx$data()
  expect_equal(w$weight[w$record_id == "7" & w$redcap_event_name == "baseline_arm_1"], 75)
  r2 <- nx$raise_queries()
  expect_equal(r2$auto_resolved, 1)
  q <- nx$queries()
  expect_equal(q$status[q$rule == "range:weight" & q$record_id == "7"], "resolved")
  expect_equal(tail(nx$query_audit(q$query_id[q$rule == "range:weight" & q$record_id == "7"]), 1)$actor, "system")
})

test_that("data dictionary drift is detected and logged", {
  nx <- demo()
  nx$backend$change_metadata("weight", "text_validation_max", "95")
  s <- nx$sync()
  expect_true(s$metadata_changed)
  h <- nx$ledger$schema_history()
  expect_match(h$summary[1], "changed: weight \\(text_validation_max\\)")
  # The new limit is enforced on the next validation without code changes.
  iss <- nx$validate()
  expect_gt(sum(iss$rule == "range:weight"), 1)
})

test_that("DET receiver re-exports a single record", {
  nx <- demo()
  nx$backend$edit("15", "sbp", "140", event = "week_12_arm_1")
  nx$on_det("15", "week_12_arm_1", "vitals")
  d <- nx$data()
  expect_equal(d$sbp[d$record_id == "15" & d$redcap_event_name == "week_12_arm_1"], 140)
})

test_that("deleted records are removed on sync", {
  nx <- demo()
  nx$backend$delete_record("3")
  nx$sync()
  expect_false("3" %in% nx$data()$record_id)
})

test_that("query lifecycle enforces transitions and reasons", {
  nx <- demo()
  id <- nx$add_query("10", "weight", "check", event = "baseline_arm_1", source = "analysis")
  expect_error(nx$transition_query(id, "answered", ""), "reason")
  nx$transition_query(id, "answered", "site replied")
  expect_error(nx$transition_query(id, "answered", "again"), "Cannot move")
  nx$transition_query(id, "resolved", "verified against source")
  nx$transition_query(id, "closed", "done")
  a <- nx$query_audit(id)
  expect_equal(a$new_status, c("open", "answered", "resolved", "closed"))
})

test_that("data cuts are hashed, signed off and tamper-evident", {
  nx <- demo()
  id <- nx$freeze("Interim")
  expect_error(nx$use_cut(id, require_signoff = TRUE), "not been signed off")
  nx$sign_off(id, "clean")
  expect_error(nx$sign_off(id, "again"), "already signed off")
  nx$use_cut(id, require_signoff = TRUE)
  nx$backend$edit("1", "weight", "99.9")
  nx$sync()
  d <- nx$data()
  expect_false(isTRUE(d$weight[d$record_id == "1" & d$redcap_event_name == "baseline_arm_1"] == 99.9))
  nx$use_cut(NULL)
  path <- file.path(nx$dir, "cuts", nx$cuts()$path[1])
  cat("tamper", file = path, append = TRUE)
  expect_error(nx$use_cut(id), "Hash mismatch")
})

test_that("reshaping casts events wide and collapses repeating forms", {
  nx <- demo()
  long <- nx$shape("long", "drop")
  expect_true(all(is.na(long$redcap_repeat_instrument %||% NA)))
  wide <- nx$shape("wide", "collapse")
  expect_equal(nrow(wide), 120)
  expect_true(all(c("sbp__baseline", "sbp__week_12", "sbp__week_24", "n_adverse_events",
                    "any_ae_serious", "max_ae_grade") %in% names(wide)))
  expect_false(any(is.na(wide$any_ae_serious)))
  expect_s3_class(wide$arm, "factor")
  v <- attr(wide, "variables")
  expect_equal(v$event[v$name == "sbp__week_12"], "week_12_arm_1")
  rep <- nx$shape("long", "only")
  expect_true(all(rep$redcap_repeat_instrument == "adverse_events"))
})

test_that("Table 1 detects the arm and chooses tests from the data", {
  nx <- demo()
  expect_equal(nx$arm(), "arm")
  t1 <- nx$table_one()
  expect_true(all(c("Drug A", "Placebo", "p_value", "test", "rationale") %in% names(t1)))
  expect_equal(t1$test[t1$variable == "height" & t1$level != "Missing"][1], "Welch t-test")
  expect_equal(t1$test[t1$variable == "age"][1], "Wilcoxon rank-sum")
  expect_equal(t1$test[t1$variable == "pregnant"][1], "Fisher's exact")
  expect_error(nx$table_one(mode = "sap"), "pre-specified")
  t2 <- nx$table_one(vars = c("age", "sex"), tests = list(age = "t.test", sex = "chisq"), mode = "sap")
  expect_equal(t2$rationale[t2$variable == "age"][1], "Pre-specified (SAP)")
})

test_that("outliers, trends and models run on the demo", {
  nx <- demo()
  o <- nx$outliers("weight")
  expect_true(any(o$outlier & o$record_id == "7"))
  tr <- nx$trend("sbp")
  expect_equal(nrow(tr), 6)
  f <- nx$fit("sbp__week_24 ~ arm + sbp__baseline", "linear")
  expect_true("armPlacebo" %in% f$term)
  cox <- nx$fit("Surv(followup_days, event_occurred == 'Yes') ~ arm", "cox")
  expect_true("hazard_ratio" %in% names(cox))
})

test_that("write-back puts open query counts into REDCap", {
  nx <- demo()
