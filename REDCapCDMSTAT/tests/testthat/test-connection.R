test_that("the connection check passes on a working project and explains each item", {
  m <- start_mock_redcap()
  on.exit(m$process$kill(), add = TRUE)
  chk <- redcap_check(m$url, token = mock_token)
  r <- stats::setNames(chk$result, chk$check)
  expect_equal(unname(r["Server and token"]), "PASS")
  expect_equal(unname(r["Data dictionary"]), "PASS")
  expect_equal(unname(r["Record export"]), "PASS")
  expect_match(chk$detail[chk$check == "Record export"], "^120 records")
  expect_equal(unname(r["Logging export (incremental sync)"]), "PASS")
  expect_match(chk$detail[chk$check == "CDMSTAT DRW External Module"], "Not installed")
  expect_false(any(chk$result == "FAIL"))
  expect_output(print(chk), "Connection works")
})

test_that("wrong tokens and unreachable servers fail with a plain explanation", {
  m <- start_mock_redcap()
  on.exit(m$process$kill(), add = TRUE)
  bad <- redcap_check(m$url, token = "FFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF")
  expect_equal(bad$result[bad$check == "Server and token"], "FAIL")
  expect_match(bad$detail[bad$check == "Server and token"], "refused the token")
  short <- redcap_check(m$url, token = "abc")
  expect_equal(short$result[short$check == "Token format"], "WARN")
  gone <- redcap_check(sprintf("http://127.0.0.1:%d", httpuv::randomPort()), token = mock_token)
  expect_equal(gone$result[gone$check == "Server and token"], "FAIL")
  expect_match(gone$detail[gone$check == "Server and token"], "could not be reached")
  expect_equal(redcap_check("redcap.example.org", token = mock_token)$detail[1], "https://redcap.example.org/api/")
})

test_that("setup saves the connection without the token and the app picks it up", {
  m <- start_mock_redcap()
  on.exit(m$process$kill(), add = TRUE)
  old <- Sys.getenv(c("REDCAP_API_TOKEN", "CDMSTAT_SOURCE", "CDMSTAT_URL", "CDMSTAT_DIR", "CDMSTAT_TOKEN_ENV"), unset = NA)
  on.exit({
    for (k in names(old)) if (is.na(old[[k]])) Sys.unsetenv(k) else do.call(Sys.setenv, stats::setNames(list(old[[k]]), k))
  }, add = TRUE)
  dir <- tempfile("conn")
  nx <- suppressMessages(cdmstat_setup(m$url, token = mock_token, store = "session", dir = dir))
  expect_output(print(nx), "records: 120")
  expect_equal(nx$summary()$source, "REDCap API")
  saved <- readLines(file.path(dir, "connection.json"))
  expect_false(any(grepl(mock_token, saved, fixed = TRUE)))
  expect_equal(cdmstat_connection(dir)$url, m$url)
  expect_no_match(nx$script(), mock_token, fixed = TRUE)

  # Like a fresh app start: only the data folder is known.
  Sys.unsetenv(c("CDMSTAT_SOURCE", "CDMSTAT_URL"))
  Sys.setenv(CDMSTAT_DIR = dir)
  ny <- cdmstat_from_env()
  expect_equal(ny$summary()$source, "REDCap API")
  expect_equal(ny$summary()$records, 120)

  cdmstat_disconnect(dir)
  expect_null(cdmstat_connection(dir))
})

test_that("a REDCap edit is picked up by incremental sync and write-back reaches REDCap", {
  m <- start_mock_redcap()
  on.exit(m$process$kill(), add = TRUE)
  Sys.setenv(CDMSTAT_TEST_TOKEN = mock_token)
  on.exit(Sys.unsetenv("CDMSTAT_TEST_TOKEN"), add = TRUE)
  nx <- cdmstat_connect(m$url, token_env = "CDMSTAT_TEST_TOKEN", dir = tempfile("live"))
  expect_true(any(nx$validate()$rule == "range:weight"))
  m$edit("7", "baseline_arm_1", "weight", "75.0")
  s <- nx$sync()
  expect_equal(s$mode, "incremental")
  expect_equal(s$changed, 1)
  expect_false(any(nx$validate()$rule == "range:weight" & nx$validate()$record_id == "7"))
  nx$raise_queries()
  n <- nx$writeback()
  expect_gt(n, 0)
  back <- RedcapBackend$new(m$url, mock_token)$records("22")
  expect_equal(back$cdmstat_open_queries[back$redcap_event_name == "baseline_arm_1"], "1")
})

test_that("without the logging right, sync falls back to a full download", {
  m <- start_mock_redcap(log_access = FALSE)
  on.exit(m$process$kill(), add = TRUE)
  chk <- redcap_check(m$url, token = mock_token)
  expect_equal(chk$result[chk$check == "Logging export (incremental sync)"], "WARN")
  Sys.setenv(CDMSTAT_TEST_TOKEN = mock_token)
  on.exit(Sys.unsetenv("CDMSTAT_TEST_TOKEN"), add = TRUE)
  nx <- cdmstat_connect(m$url, token_env = "CDMSTAT_TEST_TOKEN", dir = tempfile("nolog"))
  m$edit("15", "week_12_arm_1", "sbp", "140")
  s <- nx$sync()
  expect_equal(s$mode, "full (no log access)")
  d <- nx$data()
  expect_equal(d$sbp[d$record_id == "15" & d$redcap_event_name == "week_12_arm_1"], 140)
})
